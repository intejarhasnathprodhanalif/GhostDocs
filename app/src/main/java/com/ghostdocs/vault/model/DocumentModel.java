package com.ghostdocs.vault.model;

import org.json.JSONArray;
import org.json.JSONException;
import org.json.JSONObject;

import java.io.File;
import java.text.SimpleDateFormat;
import java.util.ArrayList;
import java.util.Date;
import java.util.List;
import java.util.Locale;
import java.util.Objects;

/**
 * DocumentModel — Secure Document Data Transfer Object
 *
 * <p>Represents a single encrypted document stored in the GhostDocs vault.
 * Each instance maps 1-to-1 with a document in the Firestore collection:
 * {@code users/{userId}/documents/{docId}}.
 *
 * <p><b>OOP Design — Encapsulation:</b>
 * <ul>
 *   <li>All fields are {@code private}. Access is controlled via
 *       public getters and setters, preventing uncontrolled mutation.</li>
 *   <li>{@link #toJson()} serialises the model to a {@link JSONObject} using
 *       the native {@code org.json} API (no third-party serialiser).</li>
 *   <li>The no-arg constructor is <b>required</b> for Firestore's
 *       {@code DocumentSnapshot.toObject(DocumentModel.class)} auto-mapping
 *       via reflection. Without it, Firestore throws a runtime exception.</li>
 * </ul>
 *
 * <p><b>Document Type Constants:</b> Use the {@code TYPE_*} string constants when
 * setting {@link #setDocType(String)} to maintain consistency with the OCR
 * classification engine (Step 5).
 */
public class DocumentModel {

    // ── Document Type Constants ───────────────────────────────────────────────
    public static final String TYPE_NID          = "NID";
    public static final String TYPE_RECEIPT      = "RECEIPT";
    public static final String TYPE_PRESCRIPTION = "PRESCRIPTION";
    public static final String TYPE_PASSWORD     = "PASSWORD";
    public static final String TYPE_STUDY_NOTE   = "STUDY_NOTE";
    public static final String TYPE_OTHER        = "OTHER";

    // ── Firestore Field Name Constants (avoid magic strings) ─────────────────
    public static final String FIELD_DOC_ID        = "docId";
    public static final String FIELD_TITLE         = "title";
    public static final String FIELD_OCR_TEXT      = "ocrText";
    public static final String FIELD_ENCRYPTED_PATH          = "encryptedPath";
    public static final String FIELD_ORIGINAL_ENCRYPTED_PATH = "originalEncryptedPath";
    public static final String FIELD_THUMBNAIL_PATH = "thumbnailPath";
    public static final String FIELD_PDF_PATH      = "pdfPath";
    public static final String FIELD_TIMESTAMP     = "timestamp";
    public static final String FIELD_TAGS          = "tags";
    public static final String FIELD_DOC_TYPE      = "docType";
    public static final String FIELD_OWNER_ID      = "ownerId";
    public static final String FIELD_SHARE_URL     = "shareUrl";

    // ── Private Fields (Encapsulation) ────────────────────────────────────────

    /** Firestore auto-generated document ID. */
    private String docId;

    /** Human-readable title — derived from OCR or original filename. */
    private String title;

    /** Full raw text extracted by ML Kit OCR (Step 5). */
    private String ocrText;

    /** Absolute path to the AES-encrypted file in app-private storage. */
    private String encryptedPath;

    /** Absolute path to the AES-encrypted full uncropped original image (when cropped). */
    private String originalEncryptedPath;

    /** Absolute path to a compressed thumbnail for display in the vault grid. */
    private String thumbnailPath;

    /** Absolute path to the searchable PDF generated by PdfDocument (Step 8). */
    private String pdfPath;

    /** Publicly accessible Firebase Storage download URL for web browser QR viewing. */
    private String shareUrl;

    /** Unix epoch milliseconds when this document was created. */
    private long timestamp;

    /**
     * Keyword tags extracted by the Regex engine (Step 5).
     * Examples: "NID", "TrxID:12345", "Password", "Prescription"
     */
    private List<String> tags;

    /**
     * Classified document type.
     * One of {@link #TYPE_NID}, {@link #TYPE_RECEIPT}, {@link #TYPE_PRESCRIPTION},
     * {@link #TYPE_PASSWORD}, or {@link #TYPE_OTHER}.
     */
    private String docType;

    /** Firebase Auth UID of the document owner (for Firestore security rules). */
    private String ownerId;

    // ════════════════════════════════════════════════════════════════════════
    // Constructors
    // ════════════════════════════════════════════════════════════════════════

    /**
     * No-arg constructor — REQUIRED by Firestore for automatic deserialization.
     * Do not remove.
     */
    public DocumentModel() {
        this.tags = new ArrayList<>();
    }

    /**
     * Full constructor for programmatic creation (used by the Watcher pipeline
     * in Steps 4–8).
     *
     * @param docId          Firestore document ID (or null for auto-assign)
     * @param title          human-readable document title
     * @param ocrText        full OCR text
     * @param encryptedPath  path to encrypted file
     * @param thumbnailPath  path to thumbnail image
     * @param pdfPath        path to PDF file
     * @param timestamp      creation time in epoch ms
     * @param tags           list of keyword tags
     * @param docType        one of the {@code TYPE_*} constants
     * @param ownerId        Firebase Auth UID
     */
    public DocumentModel(String docId, String title, String ocrText,
                         String encryptedPath, String thumbnailPath, String pdfPath,
                         long timestamp, List<String> tags,
                         String docType, String ownerId) {
        this.docId          = docId;
        this.title          = title;
        this.ocrText        = ocrText;
        this.encryptedPath  = encryptedPath;
        this.thumbnailPath  = thumbnailPath;
        this.pdfPath        = pdfPath;
        this.timestamp      = timestamp;
        this.tags           = tags != null ? tags : new ArrayList<>();
        this.docType        = docType;
        this.ownerId        = ownerId;
    }

    // ════════════════════════════════════════════════════════════════════════
    // Getters — required for Firestore field mapping
    // ════════════════════════════════════════════════════════════════════════

    public String getDocId()          { return docId; }
    public String getTitle()          { return title; }
    public String getOcrText()        { return ocrText; }
    public String getEncryptedPath()          { return encryptedPath; }
    public String getOriginalEncryptedPath()  { return originalEncryptedPath; }
    public String getThumbnailPath()  { return thumbnailPath; }
    public String getPdfPath()        { return pdfPath; }
    public long   getTimestamp()      { return timestamp; }
    public List<String> getTags()     { return tags; }
    public String getDocType()        { return docType; }
    public String getOwnerId()        { return ownerId; }
    public String getShareUrl()       { return shareUrl; }

    // ════════════════════════════════════════════════════════════════════════
    // Setters
    // ════════════════════════════════════════════════════════════════════════

    public void setDocId(String docId)                  { this.docId = docId; }
    public void setTitle(String title)                  { this.title = title; }
    public void setOcrText(String ocrText)              { this.ocrText = ocrText; }
    public void setEncryptedPath(String encryptedPath)                 { this.encryptedPath = encryptedPath; }
    public void setOriginalEncryptedPath(String originalEncryptedPath) { this.originalEncryptedPath = originalEncryptedPath; }
    public void setThumbnailPath(String thumbnailPath)  { this.thumbnailPath = thumbnailPath; }
    public void setPdfPath(String pdfPath)              { this.pdfPath = pdfPath; }
    public void setTimestamp(long timestamp)            { this.timestamp = timestamp; }
    public void setTags(List<String> tags)              { this.tags = tags; }
    public void setDocType(String docType)              { this.docType = docType; }
    public void setOwnerId(String ownerId)              { this.ownerId = ownerId; }
    public void setShareUrl(String shareUrl)            { this.shareUrl = shareUrl; }

    // ════════════════════════════════════════════════════════════════════════
    // Utility Methods
    // ════════════════════════════════════════════════════════════════════════

    /**
     * Returns the timestamp formatted as a human-readable date string.
     * Example: "Nov 6, 2026 · 10:32 AM"
     *
     * @return formatted date string, or empty string if timestamp is 0
     */
    public String getFormattedDate() {
        if (timestamp == 0) return "";
        SimpleDateFormat sdf = new SimpleDateFormat("MMM d, yyyy · hh:mm a", Locale.getDefault());
        return sdf.format(new Date(timestamp));
    }

    /**
     * Returns the first tag in the list as a short type badge string,
     * or the docType if no tags exist.
     *
     * @return a short label for display in the vault card
     */
    public String getPrimaryTag() {
        if (tags != null && !tags.isEmpty()) {
            return tags.get(0);
        }
        return docType != null ? docType : TYPE_OTHER;
    }

    /**
     * Resolves the encrypted full uncropped original file on disk if this document
     * was smart-cropped during capture.
     *
     * @return existing {@link File} for the uncropped original, or null if not cropped / unavailable.
     */
    public File resolveOriginalEncryptedFile() {
        if (originalEncryptedPath != null && !originalEncryptedPath.isEmpty()) {
            File f = new File(originalEncryptedPath);
            if (f.exists()) return f;
        }
        if (encryptedPath != null && encryptedPath.endsWith(".enc")) {
            String fallback = encryptedPath.substring(0, encryptedPath.length() - 4) + "_orig.enc";
            File f = new File(fallback);
            if (f.exists()) return f;
        }
        return null;
    }

    /**
     * Serialises this model to a {@link JSONObject} using the native
     * {@code org.json} API (no third-party JSON library).
     *
     * <p>Used by the QR code generator (Step 7) and for logging.
     *
     * @return a {@link JSONObject} representation of this document
     */
    public JSONObject toJson() {
        JSONObject json = new JSONObject();
        try {
            json.put(FIELD_DOC_ID,                  docId != null ? docId : "");
            json.put(FIELD_TITLE,                   title != null ? title : "");
            json.put(FIELD_OCR_TEXT,                ocrText != null ? ocrText : "");
            json.put(FIELD_ENCRYPTED_PATH,          encryptedPath != null ? encryptedPath : "");
            json.put(FIELD_ORIGINAL_ENCRYPTED_PATH, originalEncryptedPath != null ? originalEncryptedPath : "");
            json.put(FIELD_THUMBNAIL_PATH, thumbnailPath != null ? thumbnailPath : "");
            json.put(FIELD_PDF_PATH,       pdfPath != null ? pdfPath : "");
            json.put(FIELD_TIMESTAMP,      timestamp);
            json.put(FIELD_DOC_TYPE,       docType != null ? docType : TYPE_OTHER);
            json.put(FIELD_OWNER_ID,       ownerId != null ? ownerId : "");
            json.put(FIELD_SHARE_URL,      shareUrl != null ? shareUrl : "");

            // Serialize tags list to JSONArray
            JSONArray tagsArray = new JSONArray();
            if (tags != null) {
                for (String tag : tags) {
                    tagsArray.put(tag);
                }
            }
            json.put(FIELD_TAGS, tagsArray);

        } catch (JSONException e) {
            // org.json only throws for null keys — this cannot happen here
            e.printStackTrace();
        }
        return json;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (o == null || getClass() != o.getClass()) return false;
        DocumentModel that = (DocumentModel) o;
        return Objects.equals(docId, that.docId);
    }

    @Override
    public int hashCode() {
        return Objects.hash(docId);
    }

    /**
     * Returns a compact summary string — useful for logging and debugging.
     */
    @Override
    public String toString() {
        return "DocumentModel{"
                + "docId='" + docId + '\''
                + ", title='" + title + '\''
                + ", docType='" + docType + '\''
                + ", timestamp=" + timestamp
                + ", tags=" + tags
                + '}';
    }
}

